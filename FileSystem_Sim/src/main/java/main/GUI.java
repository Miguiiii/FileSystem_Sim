    private void setupTree() {
        rootNode = new DefaultMutableTreeNode("Root");
        treeModel = new DefaultTreeModel(rootNode);
        jTree1.setModel(treeModel);
        updateLocationComboBox();
    }

    private void updateLocationComboBox() {
        jComboBoxUbicacion.removeAllItems();
        addFolderNodesToComboBox(rootNode);
    }

    private void addFolderNodesToComboBox(DefaultMutableTreeNode node) {
        if (node.getAllowsChildren()) {
            jComboBoxUbicacion.addItem(node);
        }
        Enumeration<?> children = node.children();
        while (children.hasMoreElements()) {
            DefaultMutableTreeNode childNode = (DefaultMutableTreeNode) children.nextElement();
            addFolderNodesToComboBox(childNode);
        }
    }
    
