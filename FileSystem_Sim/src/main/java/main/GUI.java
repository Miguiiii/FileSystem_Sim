    private void jButtonCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCrearActionPerformed
        String nombre = jTextFieldNombre.getText().trim();
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre no puede estar vacío.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        DefaultMutableTreeNode parentNode = (DefaultMutableTreeNode) jComboBoxUbicacion.getSelectedItem();
        if (parentNode == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar una ubicación.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        DefaultMutableTreeNode newNode = new DefaultMutableTreeNode(nombre);
        if (jRadioButtonArchivo.isSelected()) {
            newNode.setAllowsChildren(false);
        } else {
            newNode.setAllowsChildren(true);
        }
        treeModel.insertNodeInto(newNode, parentNode, parentNode.getChildCount());
        jTree1.expandPath(new javax.swing.tree.TreePath(parentNode.getPath()));
        jTextFieldNombre.setText("");
        if (newNode.getAllowsChildren()) {
            updateLocationComboBox();
            jComboBoxUbicacion.setSelectedItem(newNode);
        }
    }//GEN-LAST:event_jButtonCrearActionPerformed


